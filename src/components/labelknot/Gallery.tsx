type Cell =
  | { kind: "img"; src: string }
  | { kind: "text"; line: string };

const INTERSTITIALS: Record<number, string> = {
  4: "Frames of Pure Emotion",
  9: "Love That Lives On",
  11: "Sacred Vows",
  17: "Timeless in Soft Light",
  22: "Stolen Glances",
  27: "Golden Hours",
  34: "Cherished forever.",
  42: "Quiet Grace",
  44: "Forever Yours",
};

function buildCells(): Cell[] {
  const cells: Cell[] = [];
  let imgIndex = 0;

  for (let i = 0; i < 45; i++) {
    if (INTERSTITIALS[i]) {
      cells.push({ kind: "text", line: INTERSTITIALS[i] });
    } else {
      cells.push({
        kind: "img",
        src: GALLERY_IMAGES[imgIndex % GALLERY_IMAGES.length],
      });
      imgIndex++;
    }
  }

  return cells;
}

function getPosition(i: number): string {
  const m = i % 9;
  if (m === 0) return "center 20%";
  if (m === 1) return "center 50%";
  if (m === 2) return "center 30%";
  if (m === 3) return "center 70%";
  if (m === 5) return "center 15%";
  if (m === 6) return "center 40%";
  if (m === 8) return "center 60%";
  return "center center";
}

